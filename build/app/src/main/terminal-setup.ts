import { accessSync, constants } from 'node:fs';
import { basename } from 'node:path';
import { stringify } from 'yaml';
import type { ShellKind } from '../shared/types';

export function isExecutable(path: string): boolean {
  try {
    accessSync(path, constants.X_OK);
    return true;
  } catch {
    return false;
  }
}

/** Picks the shell binary: zsh preferred for 'auto' when it is the user's shell or available. */
export function resolveShell(kind: ShellKind, envShell: string | undefined, exists: (p: string) => boolean = isExecutable): { path: string; flavor: 'zsh' | 'bash' | 'sh' } {
  const zsh = ['/usr/bin/zsh', '/bin/zsh'].find(exists);
  const bash = ['/usr/bin/bash', '/bin/bash'].find(exists);
  if (kind === 'zsh' && zsh) return { path: zsh, flavor: 'zsh' };
  if (kind === 'bash' && bash) return { path: bash, flavor: 'bash' };
  if (envShell && exists(envShell)) {
    const b = basename(envShell);
    if (b === 'zsh') return { path: envShell, flavor: 'zsh' };
    if (b === 'bash') return { path: envShell, flavor: 'bash' };
  }
  if (zsh) return { path: zsh, flavor: 'zsh' };
  if (bash) return { path: bash, flavor: 'bash' };
  return { path: '/bin/sh', flavor: 'sh' };
}

/**
 * A kubeconfig overlay listed *before* the user's file in KUBECONFIG. kubectl merges files with
 * "first wins", so this pins the current context and namespace for this shell only.
 * It references the cluster/user by name and contains no credentials. `kubectl config use-context`
 * inside the shell writes to this overlay, never to the user's kubeconfig.
 */
export function overlayKubeconfig(context: { name: string; cluster: string; user: string }, namespace: string | undefined): string {
  return stringify({
    apiVersion: 'v1',
    kind: 'Config',
    'current-context': context.name,
    contexts: [{ name: context.name, context: { cluster: context.cluster, user: context.user, ...(namespace ? { namespace } : {}) } }],
  });
}

/** Removes variables that must not leak from the Electron process into user shells. */
export function shellEnv(base: NodeJS.ProcessEnv, extra: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(base)) {
    if (v === undefined) continue;
    if (/^(ELECTRON_|K8SC_|CHROME_|GOOGLE_API_KEY$|NODE_OPTIONS$|ORIGINAL_XDG_CURRENT_DESKTOP$)/.test(k)) continue;
    out[k] = v;
  }
  return { ...out, TERM: 'xterm-256color', COLORTERM: 'truecolor', TERM_PROGRAM: 'K8sConsole', ...extra };
}

