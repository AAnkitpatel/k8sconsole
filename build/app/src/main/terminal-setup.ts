/** aws CLI suggestions for the connected ECS cluster (most useful first). */
export function buildAwsSuggestions(i: { cluster?: string; services: string[]; logGroups: string[] }): string[] {
  const c = i.cluster ? ` --cluster ${i.cluster}` : '';
  const out = [
    `aws ecs list-clusters`,
    `aws sts get-caller-identity`,
    ...(i.cluster ? [`aws ecs list-services${c}`, `aws ecs list-tasks${c}`, `aws ecs list-tasks${c} --desired-status STOPPED`, `aws ecs describe-clusters --clusters ${i.cluster} --include STATISTICS`] : []),
    `aws ecs list-task-definition-families --status ACTIVE`,
  ];
  for (const s of i.services.slice(0, 40)) {
    out.push(
      `aws ecs describe-services${c} --services ${s}`,
      `aws ecs list-tasks${c} --service-name ${s}`,
      `aws ecs update-service${c} --service ${s} --force-new-deployment`,
      `aws ecs update-service${c} --service ${s} --desired-count `,
      `aws ecs wait services-stable${c} --services ${s}`,
    );
  }
  for (const g of i.logGroups.slice(0, 40)) out.push(`aws logs tail ${g} --follow`, `aws logs tail ${g} --since 1h`);
  return [...new Set(out)].filter((l) => /^[\w ./:=,\-+<>|]+$/.test(l));
}

export function zshFiles(): Record<string, string> {
  return { '.zshenv': ZSHENV, '.zshrc': ZSHRC };
}

export interface SuggestionInput {
  namespace?: string;
  namespaces: string[];
  pods: string[];
  deployments: string[];
  statefulsets: string[];
  services: string[];
}

/** Builds context-aware kubectl command suggestions (most useful first). */
export function buildSuggestions(i: SuggestionInput): string[] {
  const ns = i.namespace;
  const n = ns ? ` -n ${ns}` : '';
  const out: string[] = [
    `kubectl get pods${n}`,
    `kubectl get pods${n} -o wide`,
    `kubectl get pods -A`,
    `kubectl get deploy,sts,ds${n}`,
    `kubectl get svc,ingress${n}`,
    `kubectl get events${n} --sort-by=.lastTimestamp`,
    `kubectl get nodes -o wide`,
    `kubectl top pods${n}`,
    `kubectl top nodes`,
    `kubectl get all${n}`,
    `kubectl config get-contexts`,
    `kubectl api-resources`,
    `kubectl auth can-i --list${n}`,
  ];
  for (const p of i.pods.slice(0, 40)) {
    out.push(`kubectl logs -f ${p}${n}`, `kubectl describe pod ${p}${n}`, `kubectl exec -it ${p}${n} -- sh`, `kubectl get pod ${p}${n} -o yaml`);
  }
  for (const d of i.deployments.slice(0, 40)) {
    out.push(`kubectl rollout status deploy/${d}${n}`, `kubectl rollout restart deploy/${d}${n}`, `kubectl scale deploy/${d}${n} --replicas=`, `kubectl describe deploy ${d}${n}`, `kubectl logs -f deploy/${d}${n}`);
  }
  for (const s of i.statefulsets.slice(0, 20)) out.push(`kubectl rollout status sts/${s}${n}`, `kubectl describe sts ${s}${n}`);
  for (const s of i.services.slice(0, 40)) out.push(`kubectl port-forward svc/${s}${n} 8080:`, `kubectl describe svc ${s}${n}`);
  for (const x of i.namespaces.slice(0, 60)) out.push(`kubectl get pods -n ${x}`, `kubectl config set-context --current --namespace=${x}`);
  // Only safe printable characters reach the zsh array.
  return [...new Set(out)].filter((l) => /^[\w ./:=,\-+<>|]+$/.test(l));
}
