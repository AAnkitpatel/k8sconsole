import { useEffect, useMemo, useRef, useState, type ReactNode } from 'react';
import type { AssistantStatus } from '../../shared/types';
import { call, errorMessage, on } from '../lib/api';
import { Modal, useDialogs, useToast } from './Dialogs';
import { YamlEditor } from './YamlEditor';

interface Item {
  role: 'user' | 'assistant';
  text: string;
  tools: string[];
  proposals: Array<{ id: string; summary: string; yaml: string }>;
  error?: string;
}

const TOOL_LABEL: Record<string, string> = {
  get_context: 'Read context',
  list_resources: 'Listed resources',
  get_resource: 'Read YAML',
  get_events: 'Read events',
  get_pod_logs: 'Read logs',
  get_metrics: 'Read metrics',
  run_security_scan: 'Ran security scan',
  propose_change: 'Prepared a change',
};

/** Minimal, safe markdown: code blocks, inline code, bold and lists. No HTML is ever injected. */
export function renderMarkdown(text: string): ReactNode[] {
  const out: ReactNode[] = [];
  const parts = text.split(/```(?:[\w-]+)?\n?/);
  parts.forEach((part, i) => {
    if (i % 2 === 1) {
      out.push(
        <pre key={i} className="md-code">
          {part.replace(/\n$/, '')}
        </pre>,
      );
      return;
    }
    part.split(/\n{2,}/).forEach((para, j) => {
      if (!para.trim()) return;
      const lines = para.split('\n');
      const inline = (s: string, k: string) =>
        s.split(/(`[^`]+`|\*\*[^*]+\*\*)/).map((seg, n) =>
          seg.startsWith('`') && seg.endsWith('`') ? (
            <code key={`${k}${n}`}>{seg.slice(1, -1)}</code>
          ) : seg.startsWith('**') && seg.endsWith('**') ? (
            <b key={`${k}${n}`}>{seg.slice(2, -2)}</b>
          ) : (
            seg
          ),
        );
      if (lines.every((l) => /^\s*([-*]|\d+\.)\s+/.test(l))) {
        out.push(
          <ul key={`${i}-${j}`}>
            {lines.map((l, n) => (
              <li key={n}>{inline(l.replace(/^\s*([-*]|\d+\.)\s+/, ''), `${i}-${j}-${n}-`)}</li>
            ))}
          </ul>,
        );
      } else {
        out.push(<p key={`${i}-${j}`}>{lines.map((l, n) => [n > 0 ? <br key={`br${n}`} /> : null, ...inline(l, `${i}-${j}-${n}-`)])}</p>);
      }
    });
  });
  return out;
}

function ProposalDialog({ proposal, dark, onClose }: { proposal: { summary: string; yaml: string }; dark: boolean; onClose: () => void }) {
  const [yaml, setYaml] = useState(proposal.yaml);
  const [busy, setBusy] = useState(false);
  const [checked, setChecked] = useState(false);
  const [msg, setMsg] = useState<{ ok: boolean; text: string } | null>(null);
  const { confirm } = useDialogs();
  const toast = useToast();
  const run = async (dryRun: boolean) => {
    if (!dryRun && !(await confirm({ title: 'Apply proposed change', message: 'Apply these manifests to the cluster with server-side apply?', confirmLabel: 'Apply' }))) return;
    setBusy(true);
    try {
      const r = await call('resource:apply', yaml, { dryRun, mode: 'apply' });
      const failed = r.filter((x) => !x.ok);
      if (failed.length) setMsg({ ok: false, text: failed.map((f) => f.error).join('\n') });
      else {
        setMsg({ ok: true, text: dryRun ? `Dry run passed for ${r.length} object(s).` : 'Applied.' });
        if (dryRun) setChecked(true);
        else {
          toast('success', 'Proposed change applied');
          onClose();
        }
      }
    } catch (e) {
      setMsg({ ok: false, text: errorMessage(e) });
    } finally {
      setBusy(false);
    }
  };
  return (
    <Modal
      title="Review proposed change"
      wide
      onClose={onClose}
      footer={
        <>
          <button className="btn" onClick={onClose}>
            Close
          </button>
          <button className="btn" disabled={busy} onClick={() => void run(true)}>
            Dry run
          </button>
          <button className="btn btn-primary" disabled={busy || !checked} onClick={() => void run(false)} title={checked ? '' : 'Run a dry run first'}>
            Apply
          </button>
        </>
      }
    >
      <p>{proposal.summary}</p>
      <p className="muted">Generated by the AI assistant. Review every field. You can edit the YAML before applying; any edit requires a new dry run.</p>
      {msg && <div className={msg.ok ? 'inline-ok' : 'inline-error pre'}>{msg.text}</div>}
      <div className="create-editor">
        <YamlEditor
          value={yaml}
          onChange={(v) => {
            setYaml(v);
            setChecked(false);
          }}
          dark={dark}
        />
      </div>
    </Modal>
  );
}

function Setup({ status, onChange }: { status: AssistantStatus; onChange: (s: AssistantStatus) => void }) {
  const [key, setKey] = useState('');
  const [error, setError] = useState<string | null>(null);
  return (
    <div className="assistant-setup">
      <h3>Set up the AI Assistant</h3>
      <p>The assistant uses Claude to explain problems, read cluster state and draft fixes you review before anything changes.</p>
      <ul className="plain-list">
        <li>✓ Read-only tools: it cannot change the cluster by itself.</li>
        <li>✓ Secret values are never sent; credential-like environment values are redacted.</li>
        <li>• Questions and the cluster data needed to answer them are sent to the Claude API (Anthropic).</li>
      </ul>
      <label className="field">
        <span>Claude API key</span>
        <input type="password" value={key} onChange={(e) => setKey(e.target.value)} placeholder="sk-ant-…" autoComplete="off" aria-label="Claude API key" />
      </label>
      {!status.secureStorage && <div className="inline-warn">No OS keyring is available to encrypt the key. Set ANTHROPIC_API_KEY in your environment instead.</div>}
      {error && <div className="inline-error">{error}</div>}
      <button
        className="btn btn-primary"
        disabled={!key.trim() || !status.secureStorage}
        onClick={() =>
          call('assistant:setKey', key.trim())
            .then((s) => {
              setKey('');
              onChange(s);
            })
            .catch((e) => setError(errorMessage(e)))
        }
      >
        Save key
      </button>
      <p className="muted">The key is encrypted with your operating system keyring and stored only on this computer.</p>
    </div>
  );
}

const SUGGESTIONS = ['Why are pods failing in this namespace?', 'Summarize the health of this cluster.', 'What are the most important security issues to fix first?', 'Explain the selected resource and check it for problems.'];

export function AssistantPanel({ open, onClose, dark, context }: { open: boolean; onClose: () => void; dark: boolean; context: string }) {
  const [status, setStatus] = useState<AssistantStatus | null>(null);
  const [conversation, setConversation] = useState(() => crypto.randomUUID());
  const [items, setItems] = useState<Item[]>([]);
  const [input, setInput] = useState('');
  const [busy, setBusy] = useState(false);
  const [review, setReview] = useState<{ summary: string; yaml: string } | null>(null);
  const end = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (open) void call('assistant:status').then(setStatus);
  }, [open]);

  useEffect(
    () =>
      on('assistant:event', (e) => {
        if (e.conversationId !== conversation) return;
        if (e.type === 'done') return setBusy(false);
        setItems((list) => {
          const copy = [...list];
          let last = copy[copy.length - 1];
          if (!last || last.role !== 'assistant') {
            last = { role: 'assistant', text: '', tools: [], proposals: [] };
            copy.push(last);
          } else copy[copy.length - 1] = last = { ...last, tools: [...last.tools], proposals: [...last.proposals] };
          if (e.type === 'text') last.text += e.text ?? '';
          if (e.type === 'tool' && e.tool) last.tools.push(e.tool.name);
          if (e.type === 'proposal' && e.proposal) last.proposals.push(e.proposal);
          if (e.type === 'error') last.error = e.error;
          return copy;
        });
      }),
    [conversation],
  );

  useEffect(() => {
    // scrollIntoView returns a Promise in recent Chromium; never return it from an effect.
    void end.current?.scrollIntoView({ block: 'end' });
  }, [items]);

  const send = (text: string) => {
    if (!text.trim() || busy) return;
    setItems((x) => [...x, { role: 'user', text, tools: [], proposals: [] }]);
    setInput('');
    setBusy(true);
    void call('assistant:send', conversation, text, context).catch((e) => {
      setBusy(false);
      setItems((x) => [...x, { role: 'assistant', text: '', tools: [], proposals: [], error: errorMessage(e) }]);
    });
  };

  const reset = () => {
    void call('assistant:reset', conversation);
    setConversation(crypto.randomUUID());
    setItems([]);
    setBusy(false);
  };

  const ctxLine = useMemo(() => context.split('\n').slice(0, 2).join(' · '), [context]);

  return (
    <aside className="assistant" style={{ display: open ? 'flex' : 'none' }} aria-label="AI Assistant">
      <header className="assistant-head">
        <b>✦ Assistant</b>
        <span className="muted assistant-ctx" title={context}>
          {ctxLine}
        </span>
        <div className="spacer" />
        <button className="btn btn-sm" onClick={reset} disabled={!items.length}>
          New chat
        </button>
        <button className="icon-btn" aria-label="Close assistant" onClick={onClose}>
          ×
        </button>
      </header>
      {status && !status.configured ? (
        <Setup status={status} onChange={setStatus} />
      ) : (
        <>
          <div className="assistant-log" data-testid="assistant-log">
            {items.length === 0 && (
              <div className="assistant-empty">
                <p className="muted">Ask about anything in the connected cluster. Try:</p>
                {SUGGESTIONS.map((s) => (
                  <button key={s} className="chip chip-btn" onClick={() => send(s)}>
                    {s}
                  </button>
                ))}
              </div>
            )}
            {items.map((m, i) => (
              <div key={i} className={`msg msg-${m.role}`}>
                {m.tools.length > 0 && (
                  <div className="msg-tools">
                    {m.tools.map((t, j) => (
                      <span key={j} className="tag">
                        {TOOL_LABEL[t] ?? t}
                      </span>
                    ))}
                  </div>
                )}
                {m.role === 'user' ? <p>{m.text}</p> : renderMarkdown(m.text)}
                {m.proposals.map((p) => (
                  <div key={p.id} className="proposal-card">
                    <div>
                      <b>Proposed change</b> — {p.summary}
                    </div>
                    <button className="btn btn-sm btn-primary" onClick={() => setReview(p)}>
                      Review &amp; apply…
                    </button>
                  </div>
                ))}
                {m.error && <div className="inline-error">{m.error}</div>}
              </div>
            ))}
            {busy && (
              <div className="msg msg-assistant muted">
                <span className="spinner" /> Working…
              </div>
            )}
            <div ref={end} />
          </div>
          <form
            className="assistant-input"
            onSubmit={(e) => {
              e.preventDefault();
              send(input);
            }}
          >
            <textarea
              value={input}
              onChange={(e) => setInput(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === 'Enter' && !e.shiftKey) {
                  e.preventDefault();
                  send(input);
                }
              }}
              rows={3}
              placeholder="Ask about your cluster… (Enter to send, Shift+Enter for a new line)"
              aria-label="Message the assistant"
            />
            {busy ? (
              <button className="btn" type="button" onClick={() => void call('assistant:stop', conversation)}>
                Stop
              </button>
            ) : (
              <button className="btn btn-primary" type="submit" disabled={!input.trim()}>
                Send
              </button>
            )}
          </form>
        </>
      )}
      {review && <ProposalDialog proposal={review} dark={dark} onClose={() => setReview(null)} />}
    </aside>
  );
}
